"""STAGE 11 - Measurable model checks for the quality inspection report.

Writes docs/model_stats.md: dimensions/height, faces per collection, open (non-manifold)
edge counts per object, material and texture inventory.

Usage: python3 scripts/06_inspect_model.py
"""
from pathlib import Path
import bpy  # must be imported before bmesh
import bmesh
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[1]
bpy.ops.wm.open_mainfile(filepath=str(ROOT / "output" / "blend" / "character_model.blend"))

meshes = [o for o in bpy.data.objects if o.type == "MESH"]
char = [o for o in meshes if not o.users_collection[0].name.startswith("PEDESTAL")]


def bounds(objs):
    pts = [o.matrix_world @ Vector(c) for o in objs for c in o.bound_box]
    return Vector([min(p[i] for p in pts) for i in range(3)]), Vector([max(p[i] for p in pts) for i in range(3)])


lo, hi = bounds(char)
head = bpy.data.objects["Head_Skin"]
hlo, hhi = bounds([head])
lines = ["# Model statistics (generated by `scripts/06_inspect_model.py`)", ""]
lines += [f"- Character bounds: X {lo.x:.3f}…{hi.x:.3f} m, Y {lo.y:.3f}…{hi.y:.3f} m, Z {lo.z:.3f}…{hi.z:.3f} m",
          f"- Boot sole to top of skull: **{hhi.z - 0.0:.3f} m** (target 1.75 m); to the top of the hair bun: {hi.z:.3f} m",
          f"- Mesh objects: {len(meshes)}; total faces: {sum(len(o.data.polygons) for o in meshes):,}", ""]

lines += ["| Collection | Objects | Faces |", "|---|---:|---:|"]
by = {}
for o in meshes:
    c = o.users_collection[0].name
    n, f = by.get(c, (0, 0))
    by[c] = (n + 1, f + len(o.data.polygons))
for c, (n, f) in sorted(by.items()):
    lines.append(f"| {c} | {n} | {f:,} |")

lines += ["", "## Open (non-manifold) edges on the sculpted meshes", "",
          "Marching-cubes meshes should be closed. Open edges are normal on strand meshes, and on hard-surface parts only where flagged.", "",
          "| Object | Faces | Non-manifold edges |", "|---|---:|---:|"]
for o in sorted(meshes, key=lambda o: o.name):
    if o.name.startswith(("Hair_Strands", "Eyebrows", "Eyelashes", "Piping", "Boot_Laces", "Pack_", "Pouch", "Belt_B", "Belt_R",
                          "Strap_", "Goggles_L", "Goggles_F", "Goggles_B", "Goggles_H", "Earring", "Choker", "Boot_Ankle", "Boot_Eyelet", "Eye_")):
        continue
    bm = bmesh.new()
    bm.from_mesh(o.data)
    nm = sum(1 for e in bm.edges if not e.is_manifold)
    bm.free()
    lines.append(f"| {o.name} | {len(o.data.polygons):,} | {nm} |")

lines += ["", "## Materials", "", "| Material | Users | Image textures |", "|---|---:|---|"]
for m in sorted(bpy.data.materials, key=lambda m: m.name):
    if not m.users:
        continue
    imgs = sorted({n.image.name for n in m.node_tree.nodes if n.type == "TEX_IMAGE" and n.image})
    lines.append(f"| {m.name} | {m.users} | {', '.join(imgs) or '-'} |")

out = ROOT / "docs" / "model_stats.md"
out.write_text("\n".join(lines) + "\n")
print(out.read_text())
